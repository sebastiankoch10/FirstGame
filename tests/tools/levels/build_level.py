"""Build one FirstGame level's generated art and data, then register it in the GameMaker project.

Usage:
    python tests/tools/levels/build_level.py swamp            # everything
    python tests/tools/levels/build_level.py swamp --skip-ground
Outputs:
    FirstGame_ArtPack/level_<id>/props/*.png, ground/*.png, preview.png, minimap.png, layout.json
    scripts/level_layout_<id>/level_layout_<id>.gml  (generated data, do not edit)
    sprites/spr_lv_<xx>_*                             (registered resources)
"""
from __future__ import annotations

import importlib
import json
import math
import sys
import time
from concurrent.futures import ProcessPoolExecutor
from pathlib import Path

import numpy as np
from PIL import Image, ImageDraw, ImageFilter

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))

from gm_project import ROOT, Project  # noqa: E402
from pixsdf import render_fit  # noqa: E402
from worldgen import CHUNK, START, WORLD  # noqa: E402

LEVELS = {
    'swamp': {'module': 'swamp', 'ground': 'swamp_ground', 'prefix': 'spr_lv_sw_', 'texgroup': 'Level_Swamp', 'dir': 'level_swamp',
              'script': 'level_layout_swamp', 'tint': (0.62, 0.74, 0.66)},
    'ashfrost': {'module': 'ashfrost', 'ground': 'ashfrost_ground', 'prefix': 'spr_lv_af_', 'texgroup': 'Level_Ashfrost', 'dir': 'level_ashfrost',
                 'script': 'level_layout_ashfrost', 'tint': (0.62, 0.68, 0.82)},
}


def _render_prop(args):
    level, key = args
    mod = importlib.import_module(LEVELS[level]['module'])
    cat = mod.catalogue()
    builder = cat[key][0]
    img, origin = render_fit(builder(), mod.mats(), 560, 560, base=(280, 470))
    return key, img, origin


_CACHE = {}


def _bake(args):
    level, cx, cy = args
    if level not in _CACHE:  # one layout + stamp set per worker process
        mod = importlib.import_module(LEVELS[level]['module'])
        gmod = importlib.import_module(LEVELS[level]['ground'])
        layout = mod.Layout(); layout.build_coarse(8)
        _CACHE[level] = (gmod, layout, gmod.build_stamps())
    gmod, layout, stamps = _CACHE[level]
    return cx, cy, gmod.bake_chunk(layout, cx, cy, stamps)


def gml_color(rgb):
    r, g, b = rgb
    return f'make_color_rgb({int(r)},{int(g)},{int(b)})'


def write_layout_script(level, cfg, layout, props, cat, origins, sizes):
    names = sorted(cat.keys())
    index = {k: i for i, k in enumerate(names)}
    sprite_refs = ','.join(cfg['prefix'] + k for k in names)
    meta = []
    for k in names:
        _, block, sway, glow, depth, fade = cat[k]
        bk, ba, bb = 0, 0, 0
        if block:
            if block[0] == 'c':
                bk, ba = 1, block[1]
            elif block[0] == 'r':
                bk, ba, bb = 2, block[1], block[2]
            else:
                bk = 3  # composite (custom footprints, see blockers list)
        gc = glow if glow else (0, 0, 0, 0, 0)
        fw, fh = fade if fade else (0, 0)
        meta.append(f'[{bk},{ba:.1f},{bb:.1f},{int(sway)},{gml_color(gc[:3])},{gc[3]},{gc[4]},{1 if depth == "ground" else 0},{fw:.0f},{fh:.0f}]')
    flat = []
    for name, x, y, flip in props:
        flat += [str(index[name]), str(int(x)), str(int(y)), str(int(flip))]
    extra_blockers = []
    for name, x, y, flip in props:
        blk = cat[name][1]
        if blk and blk[0] == 'multi':  # composite footprints in room units: (dx, dy, radius)
            for dx, dy, rr in blk[1]:
                extra_blockers += [str(int(x + dx * flip)), str(int(y + dy)), str(int(rr))]
    hz = []
    kinds = layout.hazard_kinds
    for h in layout.hazards:
        hz += [str(kinds.index(h['kind'])), str(int(h['x'])), str(int(h['y'])), f"{h['r']:.0f}", f"{h['phase']:.2f}"]
        if 'x2' in h:
            pass
    lines = []
    for h in layout.hazards:
        if 'x2' in h:
            lines += [str(kinds.index(h['kind'])), str(int(h['x'])), str(int(h['y'])), str(int(h['x2'])), str(int(h['y2'])), f"{h['phase']:.2f}"]
    water = []
    for x, y in layout.water_points():
        water += [str(x), str(y)]
    sites = ','.join('{name:"%s",kind:"%s",x:%d,y:%d}' % (s['name'], s['kind'], s['x'], s['y']) for s in layout.sites)
    ambient = getattr(layout, 'ambient_points', lambda: [])()
    amb = []
    for kind, x, y in ambient:
        amb += [str(kind), str(int(x)), str(int(y))]

    def wrap(items, per=24):
        rows = [','.join(items[i:i + per]) for i in range(0, len(items), per)]
        return ',\n            '.join(rows)

    code = f'''/// GENERATED by tests/tools/levels/build_level.py {level} – do not edit by hand.
/// Layout seed {layout.seed}. Props [meta_index,x,y,flip], hazards [kind,x,y,r,phase], water ripple points [x,y].
function {cfg['script']}() {{
    static data = {{
        id:"{level}",
        hazard_kinds:{json.dumps(kinds)},
        sprites:[{sprite_refs}],
        meta:[
            {(','+chr(10)+'            ').join(meta)}
        ],
        props:[
            {wrap(flat)}
        ],
        blockers:[{','.join(extra_blockers)}],
        hazards:[
            {wrap(hz, 25)}
        ],
        hazard_lines:[{','.join(lines)}],
        water:[
            {wrap(water, 32)}
        ],
        ambient:[{wrap(amb, 30)}],
        sites:[{sites}]
    }};
    return data;
}}
'''
    return code


def composite(level, cfg, layout, props, cat, prop_imgs, origins, ground_dir, rect, out_size, tint=True, fog=True):
    x0, y0, x1, y1 = rect
    canvas = Image.new('RGBA', (x1 - x0, y1 - y0), (0, 0, 0, 255))
    for cy in range(y0 // CHUNK, (y1 - 1) // CHUNK + 1):
        for cx in range(x0 // CHUNK, (x1 - 1) // CHUNK + 1):
            ch = Image.open(ground_dir / f'chunk_{cx:02d}_{cy:02d}.png').convert('RGBA')
            canvas.alpha_composite(ch, (cx * CHUNK - x0, cy * CHUNK - y0))
    items = sorted([p for p in props if x0 - 300 < p[1] < x1 + 300 and y0 - 100 < p[2] < y1 + 400], key=lambda p: (0 if cat[p[0]][4] == 'ground' else 1, p[2]))
    for name, x, y, flip in items:
        im = prop_imgs[name]; ox, oy = origins[name]
        if flip < 0:
            im = im.transpose(Image.FLIP_LEFT_RIGHT); ox = im.width - ox
        _paste_clip(canvas, im, int(x - x0 - ox), int(y - y0 - oy))
    if tint:
        arr = np.asarray(canvas).astype(np.float32)
        arr[:, :, 0:3] *= np.array(cfg['tint'])
        canvas = Image.fromarray(np.clip(arr, 0, 255).astype(np.uint8), 'RGBA')
    return canvas.resize(out_size, Image.LANCZOS if out_size[0] < canvas.width // 2 else Image.NEAREST)


def _paste_clip(canvas, im, x, y):
    sx = max(0, -x); sy = max(0, -y)
    ex = min(im.width, canvas.width - x); ey = min(im.height, canvas.height - y)
    if sx >= ex or sy >= ey:
        return
    crop = im.crop((sx, sy, ex, ey))
    canvas.alpha_composite(crop, (max(0, x), max(0, y)))


def main():
    level = sys.argv[1]
    cfg = LEVELS[level]
    skip_ground = '--skip-ground' in sys.argv
    skip_props = '--skip-props' in sys.argv
    mod = importlib.import_module(cfg['module'])
    out = ROOT / 'FirstGame_ArtPack' / cfg['dir']
    (out / 'props').mkdir(parents=True, exist_ok=True); (out / 'ground').mkdir(parents=True, exist_ok=True)
    t0 = time.time()
    layout = mod.Layout(); layout.build_coarse(8); props = layout.scatter()
    cat = mod.catalogue()
    print(f'[{level}] layout: {len(props)} props, {len(layout.hazards)} hazards, {len(layout.sites)} sites ({time.time() - t0:.1f}s)', flush=True)
    origins = {}; prop_imgs = {}
    meta_path = out / 'props' / 'origins.json'
    with ProcessPoolExecutor(max_workers=16) as ex:
        if not skip_props:
            t1 = time.time()
            for key, img, origin in ex.map(_render_prop, [(level, k) for k in sorted(cat)]):
                Image.fromarray(img, 'RGBA').save(out / 'props' / f'{key}.png', optimize=True)
                origins[key] = [int(origin[0]), int(origin[1])]
            meta_path.write_text(json.dumps(origins, indent=1), encoding='utf-8')
            print(f'[{level}] rendered {len(cat)} props ({time.time() - t1:.1f}s)', flush=True)
        else:
            origins = json.loads(meta_path.read_text(encoding='utf-8'))
        if not skip_ground:
            t2 = time.time()
            jobs = [(level, cx, cy) for cy in range(WORLD // CHUNK) for cx in range(WORLD // CHUNK)]
            for cx, cy, img in ex.map(_bake, jobs):
                Image.fromarray(img, 'RGBA').save(out / 'ground' / f'chunk_{cx:02d}_{cy:02d}.png', optimize=True)
            print(f'[{level}] baked {len(jobs)} ground chunks ({time.time() - t2:.1f}s)', flush=True)
    for k in cat:
        prop_imgs[k] = Image.open(out / 'props' / f'{k}.png').convert('RGBA')
    # Previews from the actual generated world (ground + props, approximate ambient tint).
    px, py = layout.preview_center()
    rect = (int(px - 480), int(py - 270), int(px + 480), int(py + 270))
    composite(level, cfg, layout, props, cat, prop_imgs, origins, out / 'ground', rect, (384, 216)).save(out / 'preview.png')
    composite(level, cfg, layout, props, cat, prop_imgs, origins, out / 'ground', (int(START[0] - 400), int(START[1] - 300), int(START[0] + 400), int(START[1] + 300)), (800, 600)).save(out / 'start_view.png')
    mini = Image.new('RGBA', (WORLD // 16, WORLD // 16))
    for cy in range(8):
        for cx in range(8):
            ch = Image.open(out / 'ground' / f'chunk_{cx:02d}_{cy:02d}.png').convert('RGBA').resize((32, 32), Image.BOX)
            mini.alpha_composite(ch, (cx * 32, cy * 32))
    mini.save(out / 'minimap.png')
    (out / 'layout.json').write_text(json.dumps({'seed': layout.seed, 'sites': layout.sites, 'hazards': layout.hazards, 'props': props}, indent=1), encoding='utf-8')
    # GameMaker registration.
    proj = Project()
    proj.ensure_texture_group(cfg['texgroup'])
    for k in sorted(cat):
        proj.sprite(cfg['prefix'] + k, [out / 'props' / f'{k}.png'], origins[k], texgroup=cfg['texgroup'])
    frames = [out / 'ground' / f'chunk_{cx:02d}_{cy:02d}.png' for cy in range(8) for cx in range(8)]
    proj.sprite(cfg['prefix'] + 'ground', frames, (0, 0), texgroup=cfg['texgroup'])
    proj.sprite(cfg['prefix'] + 'preview', [out / 'preview.png'], (192, 108))
    proj.sprite(cfg['prefix'] + 'minimap', [out / 'minimap.png'], (0, 0))
    code = write_layout_script(level, cfg, layout, props, cat, origins, None)
    proj.script(cfg['script'], code)
    proj.save()
    print(f'[{level}] registered {len(proj.added)} new resources; total {time.time() - t0:.1f}s', flush=True)


if __name__ == '__main__':
    main()
