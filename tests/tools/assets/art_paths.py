"""Central path table for the source art under FirstGame_ArtPack (docs/Design/Assets & Pipeline.md, section 4).

Every tool reads its source folders only from here, so a later move (git mv, step 3 of the migration plan)
changes this file alone. Usage from any tool:

    sys.path.insert(0, str(ROOT / 'tests' / 'tools' / 'assets')); import art_paths as AP
    frames = AP.DRAGON_BOSS / 'frames'

`python tests/tools/assets/art_paths.py --check` lists every constant with its existence and reports code
references to the art folder outside this table (comments and docstrings excluded).
"""
from __future__ import annotations

import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[3]
ART = ROOT / 'FirstGame_ArtPack'

# references and legacy (read-only)
REFERENCES = ART / 'references'
LEGACY = ART / '_legacy'
# characters
SWORDSMAN_V3 = ART / 'characters' / 'swordsman_v3'
CLASS_OVERHAUL = ART / 'characters' / 'class_overhaul'
CHARACTER_LAYERS = ART / 'characters' / 'character_layers'          # generated by tests/tools/characters
# enemies and bosses
MASTER_WORLD = ART / 'environment' / 'master_world'                  # forest world incl. skeleton frames
LEVEL_ENEMIES = ART / 'enemies' / 'level_enemies'                # generated by tests/tools/levels/build_enemies.py
DRAGON_BOSS = ART / 'bosses' / 'dragon_boss'                    # originals: never modify
BOSS_V2 = ART / 'bosses' / 'boss_v2'
# live source of the miniboss models (golem, dragon), magnet orb and coin; the knight v2 sheets inside are unused.
# Kept whole (import_atmosphere_art.py reads it as one); the dragon_boss sources reference ../atmosphere_v2/frames.
ATMOSPHERE_V2 = ART / 'bosses' / 'atmosphere_v2'
# effects and environment
SPELL_V2 = ART / 'vfx' / 'spell_v2'
SPELL_CATALOG = SPELL_V2 / 'catalog.json'
ENVIRONMENT = ART / 'environment' / 'environment'


def level_dir(name: str) -> Path:
    """Generated level art folder (level_forest, level_swamp, level_ashfrost)."""
    return ART / 'environment' / name


def _code_refs():
    """Code lines (not comments or docstrings) outside this table that name the art folder."""
    hits = []
    files = list((ROOT / 'tests').rglob('*.py')) + list((ROOT / 'QA' / 'tools').glob('*.py')) + list((ROOT / 'Audio').rglob('*.py'))
    for f in files:
        if f.resolve() == Path(__file__).resolve():
            continue
        text = f.read_text(encoding='utf-8', errors='replace')
        text = re.sub(r'(\'\'\'|""")[\s\S]*?\1', '', text)       # drop docstrings
        for n, line in enumerate(text.splitlines(), 1):
            code = line.split('#', 1)[0]
            if re.search(r"""(['"/])FirstGame_ArtPack(['"/])""", code) and 'lines=[' not in code:
                hits.append(f'{f.relative_to(ROOT).as_posix()}:{n}')
    return hits


def _ps1_missing():
    """PowerShell tools cannot import this table, so they keep literal paths. Every literal FirstGame_ArtPack path in a
    .ps1 must exist (for a path continued by a variable or format placeholder: its static directory). Catches tools left
    behind by a folder move (26.11.: the prepare_*.ps1 still pointed at the pre-migration folders)."""
    checked, missing = 0, []
    files = list((ROOT / 'tests').rglob('*.ps1')) + list((ROOT / 'QA' / 'tools').glob('*.ps1')) + list((ROOT / 'Audio').rglob('*.ps1'))
    for f in files:
        if '_legacy' in f.parts:
            continue
        for n, line in enumerate(f.read_text(encoding='utf-8-sig', errors='replace').splitlines(), 1):
            for m in re.finditer(r"""FirstGame_ArtPack/([^'"+$\s{)]*)(.?)""", line.split('#', 1)[0]):
                rel, nxt = m.group(1), m.group(2)
                target = ART / rel
                if nxt in '+${' and nxt and not rel.endswith('/'):
                    target = target.parent        # dynamic continuation: only the static directory must exist
                checked += 1
                if not target.exists():
                    missing.append(f'{f.relative_to(ROOT).as_posix()}:{n} FirstGame_ArtPack/{rel}')
    return checked, missing


if __name__ == '__main__' and '--check' in sys.argv:
    for k, v in sorted(globals().items()):
        if k.isupper() and isinstance(v, Path) and k != 'ROOT':
            print(f'{k:18} {"ok " if v.exists() else "FEHLT"} {v.relative_to(ROOT).as_posix()}')
    refs = _code_refs()
    print(f'Code-Verweise ausserhalb der Tabelle: {len(refs)}')
    for r in refs:
        print('  ' + r)
    checked, missing = _ps1_missing()
    print(f'PowerShell-Pfade: {checked} geprueft, {len(missing)} fehlen')
    for r in missing:
        print('  FEHLT ' + r)
    sys.exit(1 if refs or missing else 0)
